-- 1) As tabelas usadas existem no schema TEKNISA?
SELECT t.TABELA,
       CASE WHEN a.TABLE_NAME IS NULL THEN 'NAO EXISTE' ELSE 'OK' END AS SITUACAO
FROM (
  SELECT 'ARQXMLNFE' TABELA FROM DUAL UNION ALL
  SELECT 'NOTAFISCAL' TABELA FROM DUAL UNION ALL
  SELECT 'AUTOFORNE' TABELA FROM DUAL UNION ALL
  SELECT 'ITEMAUTF' TABELA FROM DUAL UNION ALL
  SELECT 'PRODUTO' TABELA FROM DUAL UNION ALL
  SELECT 'FORNECEDOR' TABELA FROM DUAL UNION ALL
  SELECT 'PRODFORNXML' TABELA FROM DUAL UNION ALL
  SELECT 'RELACXMLAF' TABELA FROM DUAL UNION ALL
  SELECT 'PRODINCONSISTENTE' TABELA FROM D
) t
LEFT JOIN ALL_TABLES a ON a.OWNER='TEKNISA' AND a.TABLE_NAME = t.TABELA
ORDER BY SITUACAO, t.TABELA;

